function mapPreviewRectToReference(
  fixture: Fixture,
  rect: Rect,
  registration: ArtworkRegistration,
): Rect {
  return {
    left: (rect.left - fixture.previewCrop.left) * registration.scale + registration.translateX,
    top: (rect.top - fixture.previewCrop.top) * registration.scale + registration.translateY,
    width: rect.width * registration.scale,
    height: rect.height * registration.scale,
  };
}

