interface Crop {
  readonly left: number;
  readonly top: number;
  readonly width: number;
  readonly height: number;
}

interface Rect {
  readonly left: number;
  readonly top: number;
  readonly width: number;
  readonly height: number;
}

interface MeasuredGeometry {
  readonly referenceScale: { readonly x: number; readonly y: number };
  readonly cardCornerRadius: number;
  readonly elements: Readonly<Record<string, Rect>>;
  readonly textAntialiasRegions: readonly Rect[];
  readonly qrRegion: Rect | undefined;
  /**
   * Areas not generated by the production compositor. These are allowed only
   * in the Poster artwork-only comparison, where Apple overlays material and
   * the primary logo on top of the production Poster pixels.
   */
  readonly artworkOnlyExcludedRegions?: readonly Rect[];
}

interface QrGeometryMeasurement {
  /** The red/accent plate boundary, not the QR modules. */
  readonly plateBounds: Rect | undefined;
  /** The black/white QR code-module square, excluding the outer quiet zone. */
  readonly dataBounds: Rect | undefined;
  /** Plate-to-module inset in reference pixels. */
  readonly quietZone:
    | {
        readonly left: number;
        readonly top: number;
        readonly right: number;
        readonly bottom: number;
      }
    | undefined;
  readonly center: { readonly x: number; readonly y: number } | undefined;
  /** Corner radius inferred from the accent outline's left edge. */
  readonly estimatedRadius: number | undefined;
}

interface QrComparisonMeasurement {
  readonly reference: QrGeometryMeasurement;
  readonly production: QrGeometryMeasurement;
  /** Audit boundary for the sole QR exclusion: code modules only. */
  readonly maskedModuleBounds: Rect | undefined;
}

interface ArtworkRegistration {
  /** Uniform source-to-reference scale; non-uniform fitting is never used here. */
  readonly scale: number;
  /** Subpixel translation in reference-artwork coordinates. */
  readonly translateX: number;
  readonly translateY: number;
  /** Independently measured axis scales, retained to expose capture anisotropy. */
  readonly axisScale: { readonly x: number; readonly y: number };
  readonly anisotropy: number;
}

