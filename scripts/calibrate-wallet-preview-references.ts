async function rawImage(input: Buffer) {
  return sharp(input)
    .rotate()
    .toColourspace("srgb")
    .flatten({ background: "#FFFFFF" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
}

/**
 * Mobile screenshots and Sharp-generated SVGs arrive through different image
 * paths. Normalize both deterministically before any registration or score:
 * orientation applied, embedded profile converted to sRGB, alpha flattened
 * onto the same white canvas, and lossless PNG output. No blur or color
 * threshold is used to improve a score.
 */
async function normalizedPng(input: Buffer): Promise<Buffer> {
  return sharp(input)
    .rotate()
    .toColourspace("srgb")
    .flatten({ background: "#FFFFFF" })
    .ensureAlpha()
    .png({ compressionLevel: 9, adaptiveFiltering: true })
    .toBuffer();
}

function uniformRegistrationSeed(
  reference: Crop,
  source: { readonly width: number; readonly height: number },
): ArtworkRegistration {
  const axisScale = {
    x: reference.width / source.width,
    y: reference.height / source.height,
  };
  const scale = (axisScale.x + axisScale.y) / 2;
  return {
    scale,
    translateX: (reference.width - source.width * scale) / 2,
    translateY: (reference.height - source.height * scale) / 2,
    axisScale,
    anisotropy: Math.abs(axisScale.x - axisScale.y) / scale,
  };
}

/**
 * Rasterizes an artwork candidate using a single affine scale and translation.
 * The SVG viewBox keeps fractional translation intact; there is deliberately no
 * per-axis resize, rotation, perspective, or other compensating warp.
 */
async function renderRegisteredArtwork(
  artwork: ComposedWalletArtwork,
  fixture: Fixture,
  registration: ArtworkRegistration,
  maximumDimension = 0,
): Promise<Buffer> {
  const source = (await normalizedPng(Buffer.from(artwork.bytes))).toString("base64");
  const reference = fixture.referenceArtworkCrop;
  const outputScale =
    maximumDimension > 0
      ? Math.min(1, maximumDimension / Math.max(reference.width, reference.height))
      : 1;
  const width = Math.max(1, Math.round(reference.width * outputScale));
  const height = Math.max(1, Math.round(reference.height * outputScale));
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${reference.width} ${reference.height}"><rect width="${reference.width}" height="${reference.height}" fill="${fixture.colors.background}"/><image href="data:image/png;base64,${source}" width="${artwork.width}" height="${artwork.height}" transform="translate(${registration.translateX} ${registration.translateY}) scale(${registration.scale})"/></svg>`;
  return normalizedPng(Buffer.from(svg, "utf8"));
}

/** Applies the same allowed uniform registration to a rasterized dashboard card. */
async function renderRegisteredPreviewCard(
  card: Buffer,
  fixture: Fixture,
  registration: ArtworkRegistration,
  maximumDimension = 0,
): Promise<Buffer> {
  const source = await rawImage(card);
  const reference = fixture.referenceCrop;
  const outputScale =
    maximumDimension > 0
      ? Math.min(1, maximumDimension / Math.max(reference.width, reference.height))
      : 1;
  const width = Math.max(1, Math.round(reference.width * outputScale));
  const height = Math.max(1, Math.round(reference.height * outputScale));
  const dataUri = (await normalizedPng(card)).toString("base64");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${reference.width} ${reference.height}"><image href="data:image/png;base64,${dataUri}" width="${source.info.width}" height="${source.info.height}" transform="translate(${registration.translateX} ${registration.translateY}) scale(${registration.scale})"/></svg>`;
  return normalizedPng(Buffer.from(svg, "utf8"));
}

async function quickSimilarity(reference: Buffer, preview: Buffer): Promise<number> {
  const [referenceRaw, previewRaw] = await Promise.all([rawImage(reference), rawImage(preview)]);
  if (
    referenceRaw.info.width !== previewRaw.info.width ||
    referenceRaw.info.height !== previewRaw.info.height
  ) {
    throw new Error("Registration candidates must share comparison dimensions.");
  }
  let difference = 0;
  for (let index = 0; index < referenceRaw.data.length; index += 4) {
    difference +=
      Math.abs(referenceRaw.data[index] - previewRaw.data[index]) +
      Math.abs(referenceRaw.data[index + 1] - previewRaw.data[index + 1]) +
      Math.abs(referenceRaw.data[index + 2] - previewRaw.data[index + 2]);
  }
  return 1 - difference / (referenceRaw.info.width * referenceRaw.info.height * 3 * 255);
}

/**
 * Finds the best permitted capture registration around the measured art slot.
 * The coarse and fine grids are intentionally small: their job is to expose
 * DPR/raster offset, never to conceal a real layout error.
 */
async function estimateArtworkRegistration(
  reference: Buffer,
  artwork: ComposedWalletArtwork,
  fixture: Fixture,
): Promise<ArtworkRegistration> {
  const seed = uniformRegistrationSeed(fixture.referenceArtworkCrop, artwork);
  const referenceSmall = await sharp(reference)
    .resize({ width: 240, height: 240, fit: "inside", kernel: sharp.kernel.lanczos3 })
    .png()
    .toBuffer();
  let best = seed;
  let bestSimilarity = -Infinity;
  const search = async (
    scaleOffsets: readonly number[],
    translations: readonly number[],
    base: ArtworkRegistration,
  ) => {
    for (const scaleOffset of scaleOffsets) {
      for (const translateXOffset of translations) {
        for (const translateYOffset of translations) {
          const candidate: ArtworkRegistration = {
            ...base,
            scale: base.scale + scaleOffset,
            translateX: base.translateX + translateXOffset,
            translateY: base.translateY + translateYOffset,
          };
          const rendered = await renderRegisteredArtwork(artwork, fixture, candidate, 240);
          const score = await quickSimilarity(referenceSmall, rendered);
          if (score > bestSimilarity) {
            best = candidate;
            bestSimilarity = score;
          }
        }
      }
    }
  };
  await search([-0.003, -0.002, -0.001, 0, 0.001, 0.002, 0.003], [-1, -0.5, 0, 0.5, 1], seed);
  const coarseBest = best;
  bestSimilarity = -Infinity;
  await search([-0.0008, -0.0004, 0, 0.0004, 0.0008], [-0.5, -0.25, 0, 0.25, 0.5], coarseBest);
  return best;
}

